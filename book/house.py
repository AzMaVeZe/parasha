def apply_edits(chs):
    """EDITS על כל הפרקים (פסקאות והערות). מחזיר רשימת שגיאות: נוסח שלא נמצא פעם אחת בדיוק."""
    errors = []
    by = {}
    for ch in chs:
        by.setdefault(ch['title'], ch)
    for title, old, new in EDITS:
        ch = by.get(title)
        if ch is None:
            errors.append(f'אין פרק {title}')
            continue
        texts = ch['paras'] + [n['text'] for n in ch['notes']]
        n = sum(t.count(old) for t in texts)
        if n != 1:
            errors.append(f'{title}: "{old[:40]}" נמצא {n} פעמים')
            continue
        rep = mark('chg', new, old)
        ch['paras'] = [p.replace(old, rep) for p in ch['paras']]
        for note in ch['notes']:
            note['text'] = note['text'].replace(old, rep)
        
    return errors


