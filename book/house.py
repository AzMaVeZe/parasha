NOTES = []


def mark(kind, text, note=''):
    """סימון לגרסת ההגהה. ההערה (או הנוסח הישן) נשמרת בצד, כדי שלא תשפיע על כללי הניקוי."""
    NOTES.append(note)
    return f'{MO}{kind}{len(NOTES) - 1}{MS}{text}{MC}'


def plain(t):
    """הטקסט בלי הסימונים."""
    return re.sub(MO + r'[a-z]+\d+' + MS, '', t).replace(MC, '')


def render_marks(escaped, proof):
    """אחרי html.escape: הסימונים ← <del>/<mark>. בגרסה לדפוס נשאר רק הטקסט."""
    def sub(m):
        kind, note, text = m.group(1), NOTES[int(m.group(2))], m.group(3)
        if not proof:
            return text
        if kind == 'chg':
            old = f'<del>{html.escape(note)}</del>' if note.strip() else ''
            return f'{old}<mark class="chg">{text}</mark>'
        return f'<mark class="chk">{text}</mark><span class="why">[{html.escape(note)}]</span>'
    prev = None
    while prev != escaped:              # סימון בתוך סימון
        prev = escaped
        escaped = re.sub(MO + r'([a-z]+)(\d+)' + MS + '([^' + MO + MC + ']*)' + MC, sub, escaped)
    return escaped


