def refs(t):
    """מראי מקום אחידים: (שמות יב, מ) בלי גרשיים; (בבלי, ברכות כד ע״ב)."""
    def bible(m):
        inner = re.sub(r'(?<=[%s])[״׳"\']' % HEB, '', m.group(2))
        return '(' + m.group(1) + ' ' + inner + ')'
    t = re.sub(r'\((%s),? ([^()]{1,30})\)' % BOOKS, bible, t)

    def daf(d, side):
        d = re.sub('[״׳"\']', '', d)
        return d + (' ע״א' if side in ('.', 'א') else ' ע״ב')

    def talmud(m):
        body = m.group(1)
        mm = re.fullmatch(r'(?:תלמוד )?(?:בבלי,? )?(%s),? (?:דף )?([%s״׳"\']{1,4})(?: ?ע["״]([אב])|([.:]))'
                          r'(?:\s*[-–]\s*([%s״׳"\']{1,4})(?: ?ע["״]([אב])|([.:])))?' % (MASECHTOT, HEB, HEB), body)
        if not mm:
            return m.group()
        s = 'בבלי, ' + mm.group(1) + ' ' + daf(mm.group(2), mm.group(3) or mm.group(4))
        if mm.group(5):
            s += '-' + daf(mm.group(5), mm.group(6) or mm.group(7))
        return '(' + s + ')'
    return re.sub(r'\(([^()]{4,50})\)', talmud, t)


