def geresh(t):
    """קיצור ומספר: ה' ← ה׳, וכו' ← וכו׳, ג'וב ← ג׳וב. גרש שפותח או סוגר ציטוט ('...') נשאר."""
    out, open_at = [], None
    letter = re.compile('[%s%s]' % (HEB, NIK))
    for i, c in enumerate(t):
        if c != "'":
            out.append(c)
            continue
        prev = t[i - 1] if i else ' '
        nxt = t[i + 1] if i + 1 < len(t) else ' '
        m = re.search(r'[%s%s"״]*$' % (HEB, NIK.replace('\u05BE', '')), ''.join(out))
        core = re.sub('[^%s]' % HEB, '', re.split('[-־]', m.group())[-1]) if m else ''
        if letter.match(prev) and re.match('[%s]' % HEB, nxt):
            # באמצע מילה: ג'וב, ז'בוטינסקי, צ'יפס — רק אחרי ג ז צ ת ד ש בתחילת מילה או בסופה. אחרת זה ציטוט: ה'אחר'
            if core in ('ג', 'ז', 'צ', 'ת', 'ד', 'ש') or (len(core) > 1 and core[-1] in 'גזצ' and len(core) <= 2):
                out.append('׳')
            else:
                out.append("'")
                open_at = i
        elif not letter.match(prev) and re.match('[%s]' % HEB, nxt):
            out.append("'")                                  # פותח ציטוט
            open_at = i
        elif letter.match(prev):
            abbr = core in ABBR2 or len(core) == 1
            if open_at is not None:
                single = ' ' not in t[open_at:i]
                if abbr and (nxt == "'" or (not single and "'" in t[i + 1:i + 80])):
                    out.append('׳')
                else:
                    out.append("'")
                    open_at = None
            else:
                out.append('׳' if abbr else "'")
        else:
            out.append(c)
    return ''.join(out)


def _maqaf_one(m):
    s = m.string
    i = m.start()
    j = i
    while j > 0 and re.match('[%s%s]' % (HEB, NIK), s[j - 1]):
        j -= 1
    before = s[j:m.end(1)]
    k = m.end()
    e = k
    while e < len(s) and re.match('[%s%s]' % (HEB, NIK), s[e]):
        e += 1
    after = s[k:e]
    if not (NIKUD.search(before) or NIKUD.search(after)):
        return m.group()
    if re.fullmatch('א[%s]*' % NIK, before) and after.startswith('ל'):
        return m.group(1) + '-'                              # אֱ-לֹהִים
    return m.group(1) + '־'


def dashes(t):
    t = re.sub(r'\s*--+\s*', ' – ', t)
    t = re.sub(r'(?<=\S) - (?=\S)', ' – ', t)
    return t


